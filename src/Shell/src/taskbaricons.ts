/** The 16 x 16 picture of a glyph (BGRA, straight alpha): parchment where it is drawn, dark wood all round it. */
export function glyphBitmap(name: string, scale = 1): Buffer {
  const rows = GLYPHS[name] ?? GLYPHS.stop!;
  const on = (x: number, y: number) => x >= 0 && y >= 0 && x < SIZE && y < SIZE && rows[y]![x] === '#';
  const n = SIZE * scale, out = Buffer.alloc(n * n * 4);
  for (let y = 0; y < SIZE; y++) for (let x = 0; x < SIZE; x++) {
    let c: number[] | null = null;
    if (on(x, y)) c = FILL;
    else { for (let dy = -1; dy <= 1 && !c; dy++) for (let dx = -1; dx <= 1; dx++) if (on(x + dx, y + dy)) { c = RIM; break; } }
    if (!c) continue;
    for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) { const i = ((y * scale + sy) * n + x * scale + sx) * 4; out[i] = c[0]!; out[i + 1] = c[1]!; out[i + 2] = c[2]!; out[i + 3] = c[3]!; }
  }
  return out;
}

/** A .ico file holding PNG pictures (Windows Vista and later read these), e.g. the 16 and 32 px of one glyph. */
export function icoFromPngs(pngs: { size: number; png: Buffer }[]): Buffer {
  const head = Buffer.alloc(6 + 16 * pngs.length);
  head.writeUInt16LE(0, 0); head.writeUInt16LE(1, 2); head.writeUInt16LE(pngs.length, 4);
  let at = head.length;
  pngs.forEach((p, i) => {
    const e = 6 + i * 16;
    head[e] = p.size >= 256 ? 0 : p.size; head[e + 1] = p.size >= 256 ? 0 : p.size; head[e + 2] = 0; head[e + 3] = 0;
    head.writeUInt16LE(1, e + 4); head.writeUInt16LE(32, e + 6); head.writeUInt32LE(p.png.length, e + 8); head.writeUInt32LE(at, e + 12);
    at += p.png.length;
  });
  return Buffer.concat([head, ...pngs.map((p) => p.png)]);
}

